#!/bin/bash
#
# Installed by setup-autorun.sh into /Library/Application Support/MacDoctor
# and started by launchd every time any volume is mounted.  Runs MacDoctor
# only when the paired USB drive is present.

SUPPORT="/Library/Application Support/MacDoctor"
LOCK="$SUPPORT/run.lock"
MIN_GAP=1800 # seconds; StartOnMount also fires for DMGs, network shares, ...

[ -s "$SUPPORT/token" ] || exit 0
TOKEN=$(cat "$SUPPORT/token")
sleep 3 # let the drive finish mounting

for vol in /Volumes/*; do
  [ -f "$vol/.macdoctor-token" ] || continue
  [ "$(cat "$vol/.macdoctor-token" 2>/dev/null)" = "$TOKEN" ] || continue

  # Run once per plug-in, not on every unrelated mount while it stays inserted.
  stamp="$vol/.macdoctor-lastrun"
  if [ -f "$stamp" ]; then
    last=$(cat "$stamp" 2>/dev/null)
    now=$(date +%s)
    [ -n "$last" ] && [ $((now - last)) -lt $MIN_GAP ] && continue
  fi

  mkdir "$LOCK" 2>/dev/null || exit 0 # already running
  trap 'rmdir "$LOCK" 2>/dev/null' EXIT
  date +%s > "$stamp"

  echo "$(date): running MacDoctor for $vol"
  /bin/bash "$SUPPORT/app/macdoctor.sh" --auto --report-dir "$vol/reports" </dev/null

  # Show the fresh report to the person at the Mac.
  # shellcheck disable=SC2012  # file names are generated by MacDoctor
  report=$(ls -t "$vol/reports"/MacDoctor-*.txt 2>/dev/null | head -n 1)
  user=$(stat -f%Su /dev/console)
  uid=$(id -u "$user" 2>/dev/null)
  if [ -n "$report" ] && [ -n "$uid" ] && [ "$user" != "root" ]; then
    launchctl asuser "$uid" sudo -u "$user" open -a TextEdit "$report"
  fi
  exit 0
done
exit 0
